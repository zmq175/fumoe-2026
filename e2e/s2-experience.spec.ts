import { test, expect } from '@playwright/test'
import { mockPublicApi, currentSeason, matches as baseMatches } from './fixtures'
import { s2Format } from '../src/lib/s2-format'
import { formatSchedule } from '../src/lib/season-format'
import type { PublicCharacter, PublicMatch, PublicRound } from '../src/lib/api'
const format=s2Format()
const rounds:PublicRound[]=formatSchedule(format,'2030-01-01T16:00:00.000Z').map((r,i)=>({...r,id:`s2-r${i}`,status:'scheduled'}))
const season={...currentSeason,id:'s2',name:'府萌 S2',status:'published' as const,format,startsAt:rounds[0].startsAt}
const matches:PublicMatch[]=Array.from({length:48},(_,i)=>({...baseMatches[0],id:`s2-m${i}`,roundId:rounds[0].id,status:'scheduled',startsAt:new Date(Date.parse(rounds[0].startsAt)+Math.floor(i/24)*86400000).toISOString(),endsAt:new Date(Date.parse(rounds[0].startsAt)+(Math.floor(i/24)+1)*86400000).toISOString()}))
const characters:PublicCharacter[]=[{id:'c105',name:'露西亚',game:'战双帕弥什',summary:'灰鸦小队队长',groupCode:'A',seed:1,galleryArtworkKey:null,matchArtworkKey:null,avatarArtworkKey:null,skinName:'誓焰'},...['崩坏3','崩坏：星穹铁道'].map((game,i)=>({id:`bronya-${i}`,name:'布洛妮娅',game,summary:`${game}的参赛角色`,groupCode:'B',seed:i+2,galleryArtworkKey:null,matchArtworkKey:null,avatarArtworkKey:null,skinName:game+'本季形态'}))]
async function setup(page:Parameters<typeof mockPublicApi>[0]) {
 await mockPublicApi(page,{season,rounds,matches,standings:[]})
 await page.route('**/api/public/characters*',r=>r.fulfill({json:{characters}}))
 await page.goto('/')
}
test('S2 keeps day switching in schedule, separate from voting',async({page})=>{
 await setup(page)
 await expect(page.locator('.site-header .brand em')).toHaveText('府萌 S2')
 await page.getByRole('button',{name:'对局中心',exact:true}).click()
 await expect(page.getByRole('heading',{name:'对局中心',exact:true})).toBeVisible()
 await expect(page.getByText('尚未开赛 · 首日对阵')).toBeVisible()
 await expect(page.locator('.match-card')).toHaveCount(24)
 await expect(page.locator('.match-card .vote-progress')).toHaveCount(0)
 await expect(page.locator('.fighter').first()).toHaveAttribute('aria-label',/尚未开赛/)
 await expect(page.locator('.fighter').first()).toBeDisabled()
 await expect(page.getByLabel('选择比赛日')).toHaveCount(0)
 await page.getByRole('button',{name:'查看每日赛程预告'}).click()
 await expect(page.getByRole('tab',{name:'每日赛程',exact:true})).toHaveAttribute('aria-selected','true')
 await expect(page.locator('.daily-fixture')).toHaveCount(24)
 await expect(page.getByRole('button',{name:'上一比赛日',exact:true})).toBeDisabled()
 await page.getByRole('button',{name:'下一比赛日',exact:true}).click()
 await expect(page.getByLabel('选择比赛日')).toHaveValue('s2-r0-1')
 await expect(page.locator('.daily-fixture')).toHaveCount(24)
 await expect(page.locator('.fighter')).toHaveCount(0)
 await page.getByLabel('选择比赛日').selectOption('s2-r8-0')
 await expect(page.getByRole('button',{name:'下一比赛日',exact:true})).toBeDisabled()
 await expect(page.locator('.day-summary')).toContainText('决赛 · 1 场')
 await expect(page.locator('.day-summary')).toContainText('1/30 00:00')
 await expect(page.locator('.day-summary')).toContainText('2/1 00:00')
 await expect(page.getByText('本日共 1 场，对手将在前序轮次结束后确定。')).toBeVisible()
 await page.getByRole('button',{name:'对局中心',exact:true}).click()
 await expect(page.getByLabel('选择比赛日')).toHaveCount(0)
 await expect(page.locator('.match-card')).toHaveCount(24)
})
test('encyclopedia separates same-name characters by game; keyboard closes details',async({page})=>{
 await setup(page)
 await page.getByRole('button',{name:'角色图鉴',exact:true}).click()
 await expect(page.getByRole('button',{name:'查看战双帕弥什 · 露西亚详情'})).toContainText('卫冕冠军')
 await expect(page.getByRole('button',{name:'查看战双帕弥什 · 露西亚详情'})).toContainText('灰鸦小队队长')
 await expect(page.getByRole('button',{name:'查看战双帕弥什 · 露西亚详情'})).not.toContainText('誓焰')
 await page.getByLabel('查找角色').fill('布洛妮娅')
 await expect(page.locator('.character-card')).toHaveCount(2)
 await page.getByRole('button',{name:'查看崩坏3 · 布洛妮娅详情'}).click()
 await expect(page.getByRole('dialog')).toContainText('崩坏3本季形态')
 await expect(page.getByRole('dialog')).not.toContainText('崩坏：星穹铁道本季形态')
 await page.keyboard.press('Escape')
 await expect(page.getByRole('dialog')).toHaveCount(0)
 await page.getByRole('button',{name:'查看崩坏：星穹铁道 · 布洛妮娅详情'}).click()
 await expect(page.getByRole('dialog')).toContainText('崩坏：星穹铁道本季形态')
 await page.setViewportSize({width:390,height:844})
 expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBe(true)
})

test('live match center keeps its title and voting controls',async({page})=>{
 await page.clock.setFixedTime(new Date('2030-01-01T17:00:00.000Z'))
 await mockPublicApi(page,{season:{...season,status:'live'},rounds:rounds.map((r,i)=>i===0?{...r,status:'live'}:r),matches:matches.map((m,i)=>i<24?{...m,status:'live'}:m),standings:[]})
 await page.goto('/matches')
 await expect(page.getByRole('heading',{name:'对局中心',exact:true})).toBeVisible()
 await expect(page.getByText('今日投票进行中')).toBeVisible()
 await expect(page.locator('.vote-progress')).toHaveCount(24)
 await expect(page.locator('.fighter').first()).toBeEnabled()
 await expect(page.getByLabel('选择比赛日')).toHaveCount(0)
})

test('S2 selection labels stay separate from names and recorded votes',async({page})=>{
 await page.clock.setFixedTime(new Date('2030-01-01T17:00:00.000Z'))
 await mockPublicApi(page,{viewer:{email:'voter@example.com',role:'voter'},season:{...season,status:'live'},rounds:rounds.map((r,i)=>i===0?{...r,status:'live'}:r),matches:[{...matches[0],status:'live'}],standings:[]})
 await page.goto('/matches')
 const fighter=page.locator('.fighter').first()
 await fighter.click()
 await expect(fighter).toHaveAttribute('aria-pressed','true')
 await expect(fighter.locator('.fighter__choice')).toHaveText('待提交')
 const name=await fighter.locator('strong').boundingBox(),badge=await fighter.locator('.fighter__choice').boundingBox()
 expect(name!.y+name!.height).toBeLessThan(badge!.y)
 await fighter.click()
 await expect(fighter).toHaveAttribute('aria-pressed','false')
 await expect(fighter.locator('.fighter__choice')).toHaveCount(0)
 await fighter.click()
 await page.getByRole('button',{name:'确认提交 1 场',exact:true}).click()
 const dialog=page.getByRole('dialog',{name:'确认 1 场投票'})
 await dialog.getByLabel('我已确认以上 1 场选择').check()
 await dialog.getByRole('button',{name:'提交 1 场投票',exact:true}).click()
 await expect(fighter.locator('.fighter__submitted')).toHaveText('已投票')
 await expect(fighter).toBeDisabled()
 await expect(fighter).toHaveAttribute('aria-pressed','true')
})
